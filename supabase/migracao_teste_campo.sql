-- APP-CIC: feedback semanal do teste de campo.
-- Execute depois das migrations base. O tenant sempre vem do JWT.
CREATE TABLE IF NOT EXISTS feedback_campo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id UUID NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  semana_inicio DATE NOT NULL,
  nota SMALLINT NOT NULL CHECK (nota BETWEEN 1 AND 5),
  aspectos JSONB NOT NULL DEFAULT '[]'::jsonb,
  comentario TEXT NOT NULL DEFAULT '' CHECK (char_length(comentario) <= 4000),
  recomendaria BOOLEAN NOT NULL DEFAULT false,
  interesse_site TEXT NOT NULL DEFAULT 'nao_agora' CHECK (interesse_site IN ('nao_agora', 'quero_conhecer', 'quero_orcamento')),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS feedback_campo_uma_resposta_por_semana ON feedback_campo (empresa_id, semana_inicio);
ALTER TABLE feedback_campo ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS feedback_campo_select_own ON feedback_campo;
DROP POLICY IF EXISTS feedback_campo_insert_own ON feedback_campo;
CREATE POLICY feedback_campo_select_own ON feedback_campo FOR SELECT USING (empresa_id = auth.uid());
CREATE POLICY feedback_campo_insert_own ON feedback_campo FOR INSERT WITH CHECK (empresa_id = auth.uid());

-- RLS + DEFAULT auth.uid() já impedem inserção cross-tenant. Se a instalação
-- já usa a função QA comum, ela pode receber o mesmo trigger das demais tabelas.
